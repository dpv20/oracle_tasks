class _QueuedSqlclRunner:
    """Return queued rows inside the unique markers generated by each query."""

    def __init__(self, responses: Sequence[_QueuedResponse]) -> None:
        self.responses = deque(responses)
        self.scripts: list[str] = []
        self.connections: list[str] = []
        self.timeouts: list[float | None] = []

    @property
    def pending(self) -> int:
        return len(self.responses)

    def run_script(
        self,
        connection: str,
        script_path: str | Path,
        args: list[str] | None = None,
        timeout: float | None = None,
        cancel_event: threading.Event | None = None,
    ) -> RunResult:
        del args, cancel_event
        if not self.responses:
            raise AssertionError("SQLcl was called more times than expected")

        script = Path(script_path).read_text(encoding="utf-8")
        self.scripts.append(script)
        self.connections.append(connection)
        self.timeouts.append(timeout)
        response = self.responses.popleft()
        if isinstance(response, RunResult):
            return response

        begin = re.search(r"^prompt (.+_BEGIN__)$", script, re.MULTILINE)
        end = re.search(r"^prompt (.+_END__)$", script, re.MULTILINE)
        if begin is None or end is None:
            raise AssertionError("The generated SQL script is not framed")
        rows = "\n".join(response)
        stdout = f"{begin.group(1)}\n{rows}\n{end.group(1)}\n"
        return RunResult(0, stdout, "")


class _CancellingOnLastRunner(_QueuedSqlclRunner):
    def run_script(
        self,
        connection: str,
        script_path: str | Path,
        args: list[str] | None = None,
        timeout: float | None = None,
        cancel_event: threading.Event | None = None,
    ) -> RunResult:
        result = super().run_script(
            connection,
            script_path,
            args=args,
            timeout=timeout,
            cancel_event=cancel_event,
        )
        if not self.responses and cancel_event is not None:
            cancel_event.set()
        return result


