def _oficowcg_coverage(
    upload_rows: int,
    *,
    nonnull_refs: int | None = None,
    distinct_refs: int | None = None,
    one_gic: int | None = None,
    one_output: int | None = None,
    no_output: int = 0,
    multiple_outputs: int = 0,
    orphan_branch_b: int = 0,
) -> str:
    values = (
        upload_rows,
        upload_rows if nonnull_refs is None else nonnull_refs,
        upload_rows if distinct_refs is None else distinct_refs,
        upload_rows if one_gic is None else one_gic,
        upload_rows if one_output is None else one_output,
        no_output,
        multiple_outputs,
        orphan_branch_b,
    )
    return "|".join(str(value) for value in values)


