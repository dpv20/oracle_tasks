    def test_ofdobiel_auto_archive_writes_exact_lf_utf8_payload_and_sha(self) -> None:
        body_lines = [
            "BDY;C;000000001;E;P;;;",
            "BDY;C;000000002;D;E;X01;Descripción inválida;",
        ]
        service, runner = self._service(
            ["UPLOAD_MASTER|ARCHIVE|IFDOBIEL|2"],
            ["IFDOBIEL|OFDOBIEL"],
            ["20260731|1|1"],
            [
                "P|||BDY;C;000000001;E;P;",
                "E|583031||BDY;C;000000002;D;E;",
            ],
            [
                "583031|1|"
                + "Descripci\u00f3n inv\u00e1lida".encode("utf-8").hex().upper()
            ],
            [
                "583031|1|"
                + "Descripci\u00f3n inv\u00e1lida".encode("utf-8").hex().upper()
            ],
            ["2|1|1"],
        )

        request = self._request()
        self.assertEqual(
            set(request.__dataclass_fields__),
            {
                "target",
                "process_ref_no",
                "overwrite",
                "interface_code",
                "input_file_date",
            },
        )
        result = service.generate(request)

        expected_lines = (
            "HDR;OFDOBIEL.txt;20260731;",
            *body_lines,
            "TLR;2;",
        )
        expected_payload = ("\n".join(expected_lines) + "\n").encode("utf-8")
        self.assertEqual(result.process_ref_no, "1234567")
        self.assertEqual(result.input_code, "IFDOBIEL")
        self.assertEqual(result.output_code, "OFDOBIEL")
        self.assertEqual(result.file_date, "20260731")
        self.assertIs(result.source, DataSourceChoice.ARCHIVE)
        self.assertEqual(result.body_count, 2)
        self.assertEqual(result.lines, expected_lines)
        self.assertEqual(result.output_path.name, "OFDOBIEL_20260731.TXT")
        self.assertEqual(result.output_path.read_bytes(), expected_payload)
        self.assertNotIn(b"\r", expected_payload)
        self.assertIn("Descripción inválida".encode("utf-8"), expected_payload)
        self.assertEqual(result.sha256, hashlib.sha256(expected_payload).hexdigest())
        self.assertTrue(
            any(
                "from GITA_UPLOAD_MASTER" in script
                and "trim(fld1) = 'BDY'" in script
                for script in runner.scripts
            )
        )
        self.assertEqual(runner.pending, 0)

