_QueuedResponse = Sequence[str] | RunResult


def _hex(value: str) -> str:
    return value.encode("utf-8").hex().upper()


def _oficowcg_row(
    status: str,
    fields: Sequence[str],
    *,
    error_code: str = "",
    error_params: str = "",
) -> str:
    if len(fields) != 11:
        raise AssertionError("OFICOWCG fixtures need eleven data fields")
    return "|".join(
        _hex(value)
        for value in (status, error_code, error_params, *fields)
    )


